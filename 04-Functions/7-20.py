#Define the function f(n) that returns 
# the n-th prime number. 
# A prime number is a natural number greater than 1, 
# divisible by 1 and that number.

def f(n):
    for i in range(1,n+1):
        z=range(1,)
        j=2
        while j <= z**0.5:
            if i%j==0:
                i+=1






