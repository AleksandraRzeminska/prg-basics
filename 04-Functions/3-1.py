#square root of 7
#natural logarithm of 5
#sine of 90 degrees

import math

square_root = math.sqrt(7)
print('A square root of 7 is', square_root)

natural_logaritm = math.log(5)
print('A natural logaritm of 5 is: ', natural_logaritm)

sine = math.sin(math.radians(90))
print('Sin 90 is: ', sine)